import type { Cocktail, RecipeLine, UnitId } from './types'

const r = (ingredientId: string, qty?: number, unit?: UnitId, note?: string): RecipeLine => ({
  ingredientId,
  ...(qty !== undefined && { qty }),
  ...(unit && { unit }),
  ...(note && { note }),
})
/** Ingrédient facultatif (décoration, givrage…). */
const opt = (ingredientId: string, qty?: number, unit?: UnitId, note?: string): RecipeLine => ({
  ...r(ingredientId, qty, unit, note),
  optional: true,
})
/** « Compléter avec… », avec une quantité indicative en cl si elle est connue. */
const top = (ingredientId: string, qty?: number, note?: string): RecipeLine => r(ingredientId, qty, 'top', note)

